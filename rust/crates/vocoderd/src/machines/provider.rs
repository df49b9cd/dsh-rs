//! The provider translation core: configured providers in, canonical model
//! calls out, and their streams back in.
//!
//! **Where `llm-dialect` sits.** The crate is the canonical model and the
//! translation core between three client dialects — OpenAI chat/completions,
//! OpenAI Responses, and Anthropic Messages — and one internal shape. Its
//! dataflow is a *gateway's*: a client wire body is parsed into
//! [`ItemRequest`](llm_dialect::items::ItemRequest), flattened by
//! `dialect::deflate` into the OpenAI-chat-shaped
//! [`ChatRequest`](llm_dialect::canonical::ChatRequest) an engine consumes, and
//! the engine's responses are rendered back out to the client's dialect.
//!
//! vocoderd is not a gateway. It is a **client of providers**, so it needs the
//! three quadrants the crate does not have:
//!
//! | | wire → canonical | canonical → wire |
//! |---|---|---|
//! | **request** | crate (`*/req.rs`) | **here** (all three dialects) |
//! | **response** | **here** | crate (`*/out.rs`) |
//! | **stream** | **here** | crate (`*/stream.rs`) |
//!
//! The crate's halves are the client-facing ones; ours are their inverses. So
//! this module supplies the provider direction and *consumes* the crate's
//! canonical model, its `deflate`, and its validation — which is the part of
//! the crate that is not direction-specific and the reason it is a dependency
//! rather than a reimplementation. Where the crate does supply an adjacent
//! direction, its output is used as a **round-trip oracle** in the tests below:
//! SSE is generated by the crate's own framers and must decode back to the
//! chunks that produced it, which is a stronger check than any hand-written
//! fixture.
//!
//! One case is a pure win rather than an inversion: for an OpenAI
//! chat/completions provider, `deflate`'s output *is* the wire body, because
//! `ChatRequest` is defined as the engine's own shape. That dialect's request
//! builder is therefore a call into the crate plus the provider-only fields.
//!
//! **Purity.** Everything here is `serde_json::Value` in and out. No socket, no
//! runtime, no clock. The driver performs the call; see `provider_call.rs` for
//! the effect that carries it.

use llm_dialect::canonical::PREFILL_MARKER;
use llm_dialect::dialect::deflate::items_to_chat_request;
use llm_dialect::items::{ContentItem, ItemRequest, ItemStreamMessage, Role};
use serde_json::{Value, json};

use super::llm_replay::{BlockType, FinishReason, StreamChunk};

/// Which wire dialect a configured provider speaks.
///
/// The three the crate names, and the three vocoderd routes models to. A
/// provider entry that names an unknown dialect is refused at configuration
/// time rather than defaulted, because silently speaking the wrong protocol to
/// a live endpoint fails in a way that looks like a provider outage.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProviderKind {
    /// `POST {base}/chat/completions`, `data:`-framed SSE.
    OpenAiChat,
    /// `POST {base}/responses`, named `event:`/`data:` SSE.
    OpenAiResponses,
    /// `POST {base}/messages`, named `event:`/`data:` SSE.
    Anthropic,
}

impl ProviderKind {
    /// The dialect id as it appears in configuration and on the wire.
    #[cfg_attr(not(test), allow(dead_code))]
    pub fn id(self) -> &'static str {
        match self {
            Self::OpenAiChat => "openai-chat",
            Self::OpenAiResponses => "openai-responses",
            Self::Anthropic => "anthropic-messages",
        }
    }

    /// Parse a configured dialect id.
    pub fn parse(s: &str) -> Option<Self> {
        match s {
            "openai-chat" | "openai" | "chat-completions" => Some(Self::OpenAiChat),
            "openai-responses" | "responses" => Some(Self::OpenAiResponses),
            "anthropic-messages" | "anthropic" => Some(Self::Anthropic),
            _ => None,
        }
    }

    /// The path appended to a provider's base URL.
    pub fn path(self) -> &'static str {
        match self {
            Self::OpenAiChat => "chat/completions",
            Self::OpenAiResponses => "responses",
            Self::Anthropic => "messages",
        }
    }

    /// The auth header this dialect expects.
    ///
    /// Separate from the request body because the shape genuinely differs:
    /// Anthropic uses `x-api-key` while both OpenAI surfaces use
    /// `Authorization: Bearer`. Sending the wrong one is a 401, not a 400, so
    /// getting it wrong looks like a bad credential.
    fn auth_header(self) -> (&'static str, &'static str) {
        match self {
            Self::Anthropic => ("x-api-key", ""),
            _ => ("authorization", "Bearer "),
        }
    }
}

/// One configured provider route.
#[derive(Debug, Clone, PartialEq)]
pub struct ProviderConfig {
    /// The route id a model catalog's `provider` field refers to.
    pub id: String,
    pub kind: ProviderKind,
    /// Scheme + host + any base path, with no trailing slash.
    pub base_url: String,
    /// The model name to send, which is not always the catalog's display id.
    pub model: String,
    /// Name of the environment variable holding the key — a *name*, never the
    /// key itself, so a configuration dump cannot leak a credential.
    pub api_key_env: Option<String>,
}

impl ProviderConfig {
    /// The full URL this provider's calls go to.
    pub fn url(&self) -> String {
        format!(
            "{}/{}",
            self.base_url.trim_end_matches('/'),
            self.kind.path()
        )
    }

    /// Resolve the auth header pair, or `None` when no key is configured.
    ///
    /// The key is read from the environment here rather than stored, so it
    /// exists only for the duration of a call. An empty or unset variable is
    /// `None` — a provider with no key is legitimate (a local model server),
    /// and refusing the call belongs to whoever knows whether the endpoint
    /// needs one.
    pub fn auth(&self) -> Option<(String, String)> {
        let env = self.api_key_env.as_ref()?;
        let key = std::env::var(env).ok().filter(|k| !k.is_empty())?;
        let (name, prefix) = self.kind.auth_header();
        Some((name.to_string(), format!("{prefix}{key}")))
    }
}

/// Why a provider request could not be built.
#[derive(Debug, Clone, PartialEq)]
pub enum BuildError {
    /// The canonical request itself is malformed (the crate validates it).
    Invalid(String),
    /// The dialect cannot express something in the canonical request.
    ///
    /// A real case: Anthropic's wire *requires* `max_tokens`, and there is no
    /// value the translator may invent on the caller's behalf without silently
    /// clamping a request the caller meant to be unbounded.
    ///
    /// Unreachable today — `anthropic_body` supplies the dialect's own default
    /// rather than failing — but kept as a variant because the *category* is
    /// real and a caller must be able to branch on it once a dialect gains a
    /// field it genuinely cannot express.
    #[allow(dead_code)]
    Unsupported(String),
}

impl std::fmt::Display for BuildError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Invalid(m) => write!(f, "invalid request: {m}"),
            Self::Unsupported(m) => write!(f, "unsupported for this provider: {m}"),
        }
    }
}

impl std::error::Error for BuildError {}

/// Anthropic's documented fallback when a caller sets no cap.
///
/// The crate's `require_max_tokens` deliberately makes this the *caller's*
/// decision rather than the parser's; vocoderd is that caller, and it must pick
/// one number rather than let every request fail. 4096 is Anthropic's own
/// published default for `max_tokens`.
pub const ANTHROPIC_DEFAULT_MAX_TOKENS: u32 = 4096;

/// Build the wire body for one provider call.
///
/// `stream` is forced on: every path through this module consumes an SSE
/// response, so a provider that answered non-streamed would be asking the
/// decoder to handle a body it never produces. The session log's recorded
/// calls are streams, and so is the replay provider they are derived from.
pub fn to_wire_request(
    kind: ProviderKind,
    config: &ProviderConfig,
    items: &ItemRequest,
) -> Result<Value, BuildError> {
    items.validate().map_err(BuildError::Invalid)?;
    match kind {
        ProviderKind::OpenAiChat => openai_chat_body(config, items),
        ProviderKind::Anthropic => anthropic_body(config, items),
        ProviderKind::OpenAiResponses => responses_body(config, items),
    }
}

/// OpenAI chat/completions: `deflate`'s output is already this wire shape.
///
/// The crate defines `ChatRequest` as the engine's (i.e. OpenAI chat's) shape,
/// so the only work here is serializing it and applying the two
/// provider-only differences: the model actually configured for this route
/// (which may differ from what the client asked for), and stripping the
/// `_prefill` marker, which names an intent for an engine-side sender and
/// "must never reach an upstream" per the crate's own contract.
fn openai_chat_body(config: &ProviderConfig, items: &ItemRequest) -> Result<Value, BuildError> {
    let chat = items_to_chat_request(items).map_err(|e| BuildError::Invalid(e.to_string()))?;
    let mut body = serde_json::to_value(&chat)
        .map_err(|e| BuildError::Invalid(format!("serialize chat request: {e}")))?;
    let Some(obj) = body.as_object_mut() else {
        return Err(BuildError::Invalid("chat request was not an object".into()));
    };
    obj.remove(PREFILL_MARKER);
    obj.insert("model".into(), json!(config.model));
    obj.insert("stream".into(), json!(true));
    // Ask for the usage trailer. Without it the stream carries no token counts
    // and a recorded `assistant/message` would have no `usage` to replay.
    obj.insert("stream_options".into(), json!({ "include_usage": true }));
    Ok(body)
}

/// Render one canonical message's items as Anthropic content blocks.
fn anthropic_blocks(msg: &ItemStreamMessage) -> Vec<Value> {
    let mut out = Vec::new();
    for item in &msg.items {
        match item {
            ContentItem::Text { text } => out.push(json!({ "type": "text", "text": text })),
            // Ancestors of an assistant turn: `thinking` / `redacted_thinking`
            // must lead the block list, and `signature` is opaque — it is
            // re-emitted verbatim or the block is sent unsigned, never invented.
            ContentItem::Thinking {
                text,
                signature,
                redacted_data,
                ..
            } => {
                if let Some(data) = redacted_data {
                    out.push(json!({ "type": "redacted_thinking", "data": data }));
                } else if let Some(sig) = signature {
                    out.push(json!({
                        "type": "thinking", "thinking": text, "signature": sig,
                    }));
                } else {
                    // Unsigned thinking has no Anthropic wire form. Dropping it
                    // is what the crate's own deflate does for this case, and
                    // fabricating a signature would be rejected upstream.
                }
            }
            ContentItem::ToolCall {
                id,
                name,
                arguments,
            } => out.push(json!({
                "type": "tool_use", "id": id, "name": name, "input": arguments,
            })),
            ContentItem::ToolResult {
                tool_call_id,
                content,
                is_error,
            } => out.push(json!({
                "type": "tool_result",
                "tool_use_id": tool_call_id,
                "content": content,
                "is_error": is_error,
            })),
            ContentItem::Refusal { text } => out.push(json!({ "type": "text", "text": text })),
        }
    }
    out
}

/// Anthropic Messages: the inversion the crate does not supply.
///
/// `from_anthropic` parses this shape *into* canonical; nothing renders
/// canonical back out to it, because a gateway in front of an Anthropic backend
/// never needs to. Three details are Anthropic-specific and easy to get wrong:
/// the system prompt is a top-level field rather than a message, `max_tokens`
/// is required, and content blocks are typed rather than a role/content pair.
fn anthropic_body(config: &ProviderConfig, items: &ItemRequest) -> Result<Value, BuildError> {
    // System turns are hoisted out; Anthropic has no `system` role in
    // `messages` and rejects one. The crate's parser joins system blocks with
    // newlines, so this reverses that join.
    let system: String = items
        .messages
        .iter()
        .filter(|m| m.role == Role::System)
        .flat_map(|m| {
            m.items.iter().filter_map(|i| match i {
                ContentItem::Text { text } => Some(text.as_str()),
                _ => None,
            })
        })
        .collect::<Vec<_>>()
        .join("\n");

    let mut messages = Vec::new();
    for msg in &items.messages {
        if msg.role == Role::System {
            continue;
        }
        let role = match msg.role {
            Role::Assistant => "assistant",
            // Tool results ride inside a user turn on this dialect, which is
            // why no `tool` role appears here.
            Role::User | Role::Tool => "user",
            Role::System => unreachable!("filtered above"),
        };
        let content = anthropic_blocks(msg);
        if content.is_empty() {
            continue;
        }
        messages.push(json!({ "role": role, "content": content }));
    }

    let mut body = json!({
        "model": config.model,
        "messages": messages,
        "stream": true,
        "max_tokens": items.max_tokens.unwrap_or(ANTHROPIC_DEFAULT_MAX_TOKENS),
    });
    let obj = body
        .as_object_mut()
        .expect("body is an object by construction");
    if !system.is_empty() {
        obj.insert("system".into(), json!(system));
    }
    if let Some(t) = items.temperature {
        obj.insert("temperature".into(), json!(t));
    }
    if let Some(p) = items.top_p {
        obj.insert("top_p".into(), json!(p));
    }
    if let Some(stops) = &items.stop_sequences {
        obj.insert("stop_sequences".into(), json!(stops));
    }
    if !items.tools.is_empty() {
        let tools: Vec<Value> = items
            .tools
            .iter()
            .map(|t| {
                let mut v = json!({ "name": t.name, "input_schema": t.input_schema });
                if let Some(d) = &t.description {
                    v["description"] = json!(d);
                }
                v
            })
            .collect();
        obj.insert("tools".into(), json!(tools));
    }
    if let Some(choice) = &items.tool_choice {
        use llm_dialect::items::ToolChoice;
        let wire = match choice {
            ToolChoice::Auto => json!({ "type": "auto" }),
            ToolChoice::None => json!({ "type": "none" }),
            // Anthropic spells "any tool" as `any`, not `required`.
            ToolChoice::Required => json!({ "type": "any" }),
            ToolChoice::Tool { name } => json!({ "type": "tool", "name": name }),
        };
        obj.insert("tool_choice".into(), wire);
    }
    if let Some(th) = &items.thinking
        && let Some(budget) = th.budget_tokens
    {
        obj.insert(
            "thinking".into(),
            json!({ "type": "enabled", "budget_tokens": budget }),
        );
    }
    Ok(body)
}

/// OpenAI Responses: likewise an inversion, and the least symmetric of the
/// three.
///
/// The shape is not chat-shaped: a top-level `instructions` string replaces the
/// system turn, and the conversation is a flat list of typed input items where
/// an assistant tool call and its result are *separate items* rather than parts
/// of a message. Getting that flattening wrong is what makes a resumed
/// tool-calling turn 400.
fn responses_body(config: &ProviderConfig, items: &ItemRequest) -> Result<Value, BuildError> {
    let instructions: String = items
        .messages
        .iter()
        .filter(|m| m.role == Role::System)
        .flat_map(|m| {
            m.items.iter().filter_map(|i| match i {
                ContentItem::Text { text } => Some(text.as_str()),
                _ => None,
            })
        })
        .collect::<Vec<_>>()
        .join("\n");

    let mut input: Vec<Value> = Vec::new();
    for msg in &items.messages {
        if msg.role == Role::System {
            continue;
        }
        for item in &msg.items {
            match item {
                ContentItem::Text { text } => input.push(json!({
                    "role": match msg.role {
                        Role::Assistant => "assistant",
                        _ => "user",
                    },
                    "content": text,
                })),
                ContentItem::Thinking { .. } => {
                    // Reasoning items are replayed only with their encrypted
                    // payload, which the canonical model carries separately;
                    // unsigned reasoning is not a Responses input item.
                }
                ContentItem::ToolCall {
                    id,
                    name,
                    arguments,
                } => input.push(json!({
                    "type": "function_call",
                    "call_id": id,
                    "name": name,
                    // The Responses wire carries arguments as a JSON *string*.
                    "arguments": serde_json::to_string(arguments).unwrap_or_else(|_| "{}".into()),
                })),
                ContentItem::ToolResult {
                    tool_call_id,
                    content,
                    ..
                } => input.push(json!({
                    "type": "function_call_output",
                    "call_id": tool_call_id,
                    "output": match content {
                        Value::String(s) => s.clone(),
                        other => other.to_string(),
                    },
                })),
                ContentItem::Refusal { text } => input.push(json!({
                    "role": "assistant",
                    "content": text,
                })),
            }
        }
    }

    let mut body = json!({
        "model": config.model,
        "input": input,
        "stream": true,
    });
    let obj = body
        .as_object_mut()
        .expect("body is an object by construction");
    if !instructions.is_empty() {
        obj.insert("instructions".into(), json!(instructions));
    }
    if let Some(mt) = items.max_tokens {
        obj.insert("max_output_tokens".into(), json!(mt));
    }
    if let Some(t) = items.temperature {
        obj.insert("temperature".into(), json!(t));
    }
    if let Some(p) = items.top_p {
        obj.insert("top_p".into(), json!(p));
    }
    if !items.tools.is_empty() {
        let tools: Vec<Value> = items
            .tools
            .iter()
            .map(|t| {
                let mut v = json!({
                    "type": "function", "name": t.name, "parameters": t.input_schema,
                });
                if let Some(d) = &t.description {
                    v["description"] = json!(d);
                }
                v
            })
            .collect();
        obj.insert("tools".into(), json!(tools));
    }
    Ok(body)
}

