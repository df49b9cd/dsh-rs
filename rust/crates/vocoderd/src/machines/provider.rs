    /// An Anthropic backend fronted by a chat-completions surface streams
    /// reasoning as a nested `thinking` object rather than a
    /// `reasoning_content` string. Reading only the string form would drop
    /// every reasoning token — invisible in the visible text, and wrong in the
    /// log.
    ///
    /// The body below is a verbatim capture from a live gateway.
    #[test]
    fn a_nested_thinking_delta_is_read_as_reasoning() {
        let chunks = decode_stream(
            ProviderKind::OpenAiChat,
            concat!(
                "data: {\"choices\":[{\"delta\":{\"role\":\"assistant\"},",
                "\"finish_reason\":null,\"index\":0}]}\n\n",
                "data: {\"choices\":[{\"delta\":{\"thinking\":{\"block_index\":0,",
                "\"kind\":\"thinking\",\"text\":\" let me\"}},\"finish_reason\":null,",
                "\"index\":0}]}\n\n",
                "data: {\"choices\":[{\"delta\":{\"thinking\":{\"block_index\":0,",
                "\"kind\":\"thinking\",\"text\":\" think\"}},\"finish_reason\":null,",
                "\"index\":0}]}\n\n",
                "data: {\"choices\":[{\"delta\":{\"content\":\"PONG\"},\"finish_reason\":",
                "\"stop\",\"index\":0}]}\n\n",
                "data: {\"choices\":[],\"usage\":{\"prompt_tokens\":35,",
                "\"completion_tokens\":36}}\n\n",
                "data: [DONE]\n\n",
            ),
        );
        let reasoning: String = chunks
            .iter()
            .filter_map(|c| match c {
                StreamChunk::ReasoningDelta { text, .. } => Some(text.as_str()),
                _ => None,
            })
            .collect();
        assert_eq!(reasoning, " let me think", "{chunks:?}");
        // Reasoning is its own block, distinct from the text block.
        let starts: Vec<_> = chunks
            .iter()
            .filter_map(|c| match c {
                StreamChunk::BlockStart { index, block_type } => Some((*index, *block_type)),
                _ => None,
            })
            .collect();
        assert_eq!(
            starts,
            vec![(0, BlockType::Reasoning), (1, BlockType::Text)],
            "{chunks:?}"
        );
        // The text and the finish reason share a delta; the text still lands in
        // its own block, and the stream still ends with the finish.
        let text: String = chunks
            .iter()
            .filter_map(|c| match c {
                StreamChunk::TextDelta { text, .. } => Some(text.as_str()),
                _ => None,
            })
            .collect();
        assert_eq!(text, "PONG");
        assert!(
            chunks.last().is_some_and(StreamChunk::is_finish),
            "{chunks:?}"
        );
        // The usage trailer after the finish is still kept.
        assert!(
            chunks
                .iter()
                .any(|c| matches!(c, StreamChunk::Usage { .. })),
            "{chunks:?}"
        );
    }

    /// The same delta shape must not be confused with a text delta: a
    /// `thinking` object with a `text` field is reasoning, not content.
    #[test]
    fn a_thinking_object_is_never_treated_as_visible_text() {
        let chunks = decode_stream(
            ProviderKind::OpenAiChat,
            concat!(
                "data: {\"choices\":[{\"delta\":{\"thinking\":{\"block_index\":0,",
                "\"kind\":\"thinking\",\"text\":\"secret\"}},\"finish_reason\":\"stop\"}]}\n\n",
                "data: [DONE]\n\n",
            ),
        );
        assert!(
            !chunks
                .iter()
                .any(|c| matches!(c, StreamChunk::TextDelta { .. })),
            "reasoning leaked into the visible text: {chunks:?}"
        );
    }

    /// **Round trip through the crate's own framers.** The crate renders
    /// canonical chunks *outward* to each dialect's SSE; feeding that output
    /// back through this module's decoder must recover chunks that agree on
    /// the text, the tool call, and the finish reason. This is a stronger
    /// check than a hand-written fixture, because the producer is the same
    /// code a real gateway uses.
    #[test]
    fn a_round_trip_through_the_crates_framers_recovers_the_text() {
        use llm_dialect::canonical::CanonChunk;
        use llm_dialect::dialect::openai_chat::stream::OpenAiFramer;

        let mut framer = OpenAiFramer::new("cmpl-1".into(), "test-model".into(), 0, true);
        let mut sse = String::new();
        for chunk in [
            CanonChunk {
                delta_text: "Hello".into(),
                ..Default::default()
            },
            CanonChunk {
                delta_text: " world".into(),
                ..Default::default()
            },
            CanonChunk {
                finish_reason: Some("stop".into()),
                ..Default::default()
            },
        ] {
            for segment in framer.frame_chunk(&chunk) {
                sse.push_str(&segment);
            }
        }
        for segment in framer.finish() {
            sse.push_str(&segment);
        }

        let decoded = decode_stream(ProviderKind::OpenAiChat, &sse);
        let text: String = decoded
            .iter()
            .filter_map(|c| match c {
                StreamChunk::TextDelta { text, .. } => Some(text.as_str()),
                _ => None,
            })
            .collect();
        assert_eq!(text, "Hello world", "SSE was: {sse}");
        assert_eq!(
            decoded.last(),
            Some(&StreamChunk::Finish {
                reason: FinishReason::Stop
            })
        );
    }

    /// The same round trip for Anthropic, where the crate emits explicit
    /// blocks — so the recovered indices must match the framer's own.
    #[test]
    fn a_round_trip_through_the_anthropic_framer_recovers_the_text() {
        use llm_dialect::canonical::CanonChunk;
        use llm_dialect::dialect::anthropic::stream::{
            StreamState, chunk_to_sse_events, finalize_stream,
        };

        let mut state = StreamState::new();
        let mut sse = String::new();
        for chunk in [
            CanonChunk {
                delta_text: "Hi".into(),
                ..Default::default()
            },
            CanonChunk {
                delta_text: " there".into(),
                ..Default::default()
            },
        ] {
            for (event, data) in chunk_to_sse_events(&chunk, "test-model", &mut state, "msg_1") {
                sse.push_str(&format!("event: {event}\ndata: {data}\n\n"));
            }
        }
        for (event, data) in finalize_stream(&mut state) {
            sse.push_str(&format!("event: {event}\ndata: {data}\n\n"));
        }

        let decoded = decode_stream(ProviderKind::Anthropic, &sse);
        let text: String = decoded
            .iter()
            .filter_map(|c| match c {
                StreamChunk::TextDelta { text, .. } => Some(text.as_str()),
                _ => None,
            })
            .collect();
        assert_eq!(text, "Hi there", "SSE was: {sse}");
        // Frames must be balanced: every block opened is closed.
        let starts = decoded
            .iter()
            .filter(|c| matches!(c, StreamChunk::BlockStart { .. }))
            .count();
        let ends = decoded
            .iter()
            .filter(|c| matches!(c, StreamChunk::BlockEnd { .. }))
            .count();
        assert_eq!((starts, ends), (1, 1), "{decoded:?}");
        assert_eq!(
            decoded.last(),
            Some(&StreamChunk::Finish {
                reason: FinishReason::Stop
            })
        );
    }
