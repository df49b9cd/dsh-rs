    /// A decoder fed one byte at a time must produce exactly what it produces
    /// fed all at once: a read boundary falls wherever the network puts it.
    #[test]
    fn the_sse_decoder_is_incremental_across_arbitrary_read_boundaries() {
        let body = "event: a\ndata: {\"x\":1}\n\ndata: hello\n\n";
        let mut whole = Vec::new();
        let mut d = SseDecoder::new();
        d.feed(body.as_bytes(), &mut whole);
        d.finish(&mut whole);

        for split in 0..body.len() {
            let mut parts = Vec::new();
            let mut d = SseDecoder::new();
            d.feed(&body.as_bytes()[..split], &mut parts);
            d.feed(&body.as_bytes()[split..], &mut parts);
            d.finish(&mut parts);
            assert_eq!(parts, whole, "split at byte {split} diverged");
        }
        assert_eq!(whole.len(), 2);
        assert_eq!(whole[0].event.as_deref(), Some("a"));
        assert_eq!(whole[0].data, "{\"x\":1}");
        assert_eq!(whole[1].event, None);
        assert_eq!(whole[1].data, "hello");
    }

