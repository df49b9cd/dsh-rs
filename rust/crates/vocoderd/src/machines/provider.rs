/// One decoded SSE frame.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct SseFrame {
    /// The `event:` field, when the dialect names its events.
    pub event: Option<String>,
    /// The concatenated `data:` lines, per the SSE spec (multiple `data:`
    /// lines in one frame join with `\n`).
    pub data: String,
}

/// A pure incremental SSE decoder.
///
/// The crate has no inbound parser — its `dialect::sse` is the outbound pump
/// that builds an axum `Response`, and its declared `eventsource-stream`
/// dependency is unused — so this is ours. It is a state machine over bytes
/// rather than a line splitter because a network read boundary falls wherever
/// it likes, including mid-frame and mid-UTF-8-character; carrying the partial
/// frame across calls is what makes that a non-event.
///
/// Spec details that matter in practice: `data:` values have exactly one
/// leading space stripped (not trimmed), a frame is dispatched on a blank line,
/// comment lines (`:`) are ignored, and a field with no colon has an empty
/// value. `retry:`/`id:` are parsed and discarded — this client reconnects on
/// the caller's terms, not the server's.
#[derive(Debug, Default)]
pub struct SseDecoder {
    /// Bytes of the frame being assembled, decoded as UTF-8 only once the
    /// frame is complete — a multi-byte character can straddle two reads.
    buf: Vec<u8>,
    event: Option<String>,
    data: Vec<String>,
    /// The last `data:` byte ended with a newline, which the SSE spec strips
    /// from the joined value along with the final line's.
    data_newline: bool,
}

impl SseDecoder {
    pub fn new() -> Self {
        Self::default()
    }

    /// Feed bytes, appending every complete frame to `out`.
    pub fn feed(&mut self, bytes: &[u8], out: &mut Vec<SseFrame>) {
        self.buf.extend_from_slice(bytes);
        // Consume whole lines. A trailing partial line stays in the buffer
        // until its terminator arrives, which is the whole point of buffering.
        while let Some(nl) = self.buf.iter().position(|b| *b == b'\n') {
            let mut line: Vec<u8> = self.buf.drain(..=nl).collect();
            line.pop();
            // A CRLF terminator leaves the CR behind; strip it so values do
            // not accumulate a trailing control character.
            if line.last() == Some(&b'\r') {
                line.pop();
            }
            self.line(&line, out);
        }
    }

    /// Finish the stream, emitting any frame the server left unterminated.
    ///
    /// A provider that closes the connection without the final blank line has
    /// still sent its data, and discarding it would turn a complete response
    /// into a truncated one.
    pub fn finish(&mut self, out: &mut Vec<SseFrame>) {
        if !self.buf.is_empty() {
            let line = std::mem::take(&mut self.buf);
            let line = line.strip_suffix(b"\r").unwrap_or(&line).to_vec();
            self.line(&line, out);
        }
        self.dispatch(out);
    }

    fn line(&mut self, line: &[u8], out: &mut Vec<SseFrame>) {
        // Non-UTF-8 in a field name or value is not recoverable as text, but it
        // must not poison the rest of the stream: skip the line.
        let Ok(text) = std::str::from_utf8(line) else {
            return;
        };
        if text.is_empty() {
            self.dispatch(out);
            return;
        }
        // A comment (often a keep-alive `: ping`) carries no field.
        if text.starts_with(':') {
            return;
        }
        let (field, value) = match text.split_once(':') {
            Some((f, v)) => (f, v.strip_prefix(' ').unwrap_or(v)),
            None => (text, ""),
        };
        match field {
            "event" => self.event = Some(value.to_string()),
            "data" => {
                self.data.push(value.to_string());
                self.data_newline = true;
            }
            // `id` and `retry` are parsed and dropped: this client owns its
            // own reconnect policy and has no use for the server's hints.
            _ => {}
        }
    }

    fn dispatch(&mut self, out: &mut Vec<SseFrame>) {
        if self.data.is_empty() && self.event.is_none() {
            return;
        }
        // The spec strips the newline that terminated the last `data:` line,
        // having used it to join the others.
        let mut data = self.data.join("\n");
        if self.data_newline {
            data.push('\n');
        }
        let data = data.strip_suffix('\n').unwrap_or(&data).to_string();
        self.data.clear();
        self.data_newline = false;
        out.push(SseFrame {
            event: self.event.take(),
            data,
        });
    }
}

/// Map a provider's finish reason onto the seam's vocabulary.
///
/// The three dialects disagree on spelling for the same three outcomes, and
/// `length`/`max_tokens` must land on [`FinishReason::MaxTokens`] rather than
/// `Stop`: the FSM makes a turn's ending sticky on it, so a mis-mapped
/// truncation would report a truncated turn as a complete one.
fn finish_from_wire(kind: ProviderKind, raw: &str) -> Option<FinishReason> {
    Some(match (kind, raw) {
        (ProviderKind::OpenAiChat, "stop") => FinishReason::Stop,
        (ProviderKind::OpenAiChat, "tool_calls") => FinishReason::ToolCalls,
        (ProviderKind::OpenAiChat, "length") => FinishReason::MaxTokens,
        // A filtered response is a completed call with no usable content; the
        // seam has no separate vocabulary for it and inventing an error would
        // misreport a call the provider considers successful.
        (ProviderKind::OpenAiChat, "content_filter") => FinishReason::Stop,

        (ProviderKind::OpenAiResponses, "stop") => FinishReason::Stop,
        (ProviderKind::OpenAiResponses, "tool_calls") => FinishReason::ToolCalls,
        (ProviderKind::OpenAiResponses, "max_output_tokens") => FinishReason::MaxTokens,

        (ProviderKind::Anthropic, "end_turn") => FinishReason::Stop,
        (ProviderKind::Anthropic, "stop_sequence") => FinishReason::Stop,
        (ProviderKind::Anthropic, "tool_use") => FinishReason::ToolCalls,
        (ProviderKind::Anthropic, "max_tokens") => FinishReason::MaxTokens,
        (ProviderKind::Anthropic, "refusal") => FinishReason::Stop,
        _ => return None,
    })
}

/// Whether an SSE frame's `data` is a terminal sentinel rather than JSON.
fn is_done_sentinel(data: &str) -> bool {
    data.trim() == "[DONE]"
}

/// Whether a post-finish frame still carries usage worth keeping.
///
/// OpenAI chat's usage trailer is the one frame that legitimately follows the
/// terminal chunk; everything else after a finish is ignored.
fn carries_usage(value: &Value) -> bool {
    value.get("usage").is_some_and(|u| !u.is_null())
}

/// Decode a provider's SSE stream into the seam's chunks.
///
/// This is the inverse of the crate's per-dialect framers and the piece the
/// loop actually consumes. It is stateful across frames because block indices
/// do not exist on the OpenAI wire at all (they are invented here, in
/// appearance order) and because Anthropic's blocks *do* exist but arrive as
/// separate start/delta/stop events that must be joined into the seam's
/// `BlockStart`/deltas/`BlockEnd` shape.
#[derive(Debug, Default)]
pub struct ProviderStreamDecoder {
    kind: Option<ProviderKind>,
    /// Next block index to allocate, for dialects without one.
    next_index: u64,
    /// Whether a block is currently open, for the same reason.
    open: Option<(u64, BlockType)>,
    /// Which block index each tool call id was assigned.
    tool_index: std::collections::HashMap<String, u64>,
    /// Anthropic carries `message_start` usage before any content.
    input_tokens: Option<u64>,
    /// A finish reason seen but not yet emitted.
    ///
    /// OpenAI chat reports `finish_reason` on the last *delta* and the token
    /// counts in a **separate frame that follows it**. The seam's contract is
    /// that a stream ends with its finish chunk (`derive_replay_script` refuses
    /// one that does not), so the reason is held here and emitted after the
    /// usage trailer or at end of stream — the same deferral the crate
    /// documents for the Responses terminal frame.
    pending_finish: Option<FinishReason>,
    finished: bool,
}

impl ProviderStreamDecoder {
    pub fn new(kind: ProviderKind) -> Self {
        Self {
            kind: Some(kind),
            ..Default::default()
        }
    }

    /// Flush a deferred finish reason.
    ///
    /// Must be called once no more frames can arrive — on `[DONE]` or at
    /// stream end. A stream that produced content but no terminal frame is left
    /// without one on purpose: inventing a `Stop` here would make a truncated
    /// call replay as a complete one, which is the failure
    /// `derive_replay_script` exists to refuse.
    pub fn end(&mut self, out: &mut Vec<StreamChunk>) {
        self.close_open(out);
        if let Some(reason) = self.pending_finish.take() {
            self.finished = true;
            out.push(StreamChunk::Finish { reason });
        }
    }

    /// Close any block left open by a stream that ended without its stop
    /// event, or by a dialect that never sends one.
    ///
    /// Providers do this on an upstream error mid-block. Leaving the block open
    /// would hand the assembler a response whose last block never closed, and
    /// the recorded row would replay differently from how it was produced.
    ///
    /// The block is emitted **empty on purpose**. This decoder's job is the
    /// chunk vocabulary; assembling a block's accumulated value belongs to
    /// whoever consumes the chunks, and doing it here as well would mean two
    /// places could disagree about what a block contains. The one exception is
    /// a tool call, whose arguments are the concatenated fragments and nothing
    /// else — but that too is read off the deltas by the consumer, so it stays
    /// out of here.
    fn close_open(&mut self, out: &mut Vec<StreamChunk>) {
        if let Some((index, block_type)) = self.open.take() {
            let block = match block_type {
                BlockType::Text => json!({ "type": "text", "text": "" }),
                BlockType::Reasoning => json!({ "type": "reasoning", "text": "" }),
                BlockType::ToolCall => json!({ "type": "tool-call" }),
            };
            out.push(StreamChunk::BlockEnd { index, block });
        }
    }

    /// Ensure a block of `block_type` is open, closing a different one first.
    fn ensure_open(&mut self, block_type: BlockType, out: &mut Vec<StreamChunk>) -> u64 {
        if let Some((index, open_type)) = self.open
            && open_type == block_type
        {
            return index;
        }
        self.close_open(out);
        let index = self.next_index;
        self.next_index += 1;
        self.open = Some((index, block_type));
        out.push(StreamChunk::BlockStart { index, block_type });
        index
    }

    /// Decode one frame, appending any chunks it produced.
    pub fn frame(&mut self, frame: &SseFrame, out: &mut Vec<StreamChunk>) {
        if is_done_sentinel(&frame.data) {
            self.end(out);
            return;
        }
        let Ok(value) = serde_json::from_str::<Value>(&frame.data) else {
            // A frame that is not JSON is not a chunk. Providers interleave
            // keep-alives and vendor extensions; skipping is correct, and
            // failing the whole stream on one would be wrong.
            return;
        };
        // Once a terminal chunk has been emitted only a usage trailer can still
        // add anything.
        if self.finished && !carries_usage(&value) {
            return;
        }
        let kind = self.kind.expect("kind set at construction");
        match kind {
            ProviderKind::OpenAiChat => self.openai_chat_frame(&value, out),
            ProviderKind::OpenAiResponses => {
                self.responses_frame(frame.event.as_deref(), &value, out)
            }
            ProviderKind::Anthropic => self.anthropic_frame(&value, out),
        }
    }

    /// Chat/completions deltas: one flat `choices[0].delta` per frame.
    fn openai_chat_frame(&mut self, value: &Value, out: &mut Vec<StreamChunk>) {
        // The usage trailer arrives with an empty `choices`, so usage is read
        // before the choice is required.
        if let Some(usage) = value.get("usage").filter(|u| !u.is_null()) {
            out.push(StreamChunk::Usage {
                usage: normalize_usage(ProviderKind::OpenAiChat, usage),
            });
        }
        let Some(choice) = value.get("choices").and_then(|c| c.get(0)) else {
            return;
        };
        if let Some(delta) = choice.get("delta") {
            // Reasoning arrives in one of two shapes on this surface, and both
            // are real:
            //
            // - `reasoning_content` (vLLM/DeepSeek) or `reasoning`, a plain
            //   string on the delta;
            // - a nested `thinking: {block_index, kind, text}` object, which is
            //   what an Anthropic backend fronted by a chat-completions surface
            //   emits — and, not coincidentally, the exact shape this crate's
            //   own `AnthropicFramer` produces. Verified against a live gateway
            //   rather than assumed: it sends `thinking` and no
            //   `reasoning_content` at all.
            //
            // Reading only the first shape would silently drop every reasoning
            // token from such a provider, which is invisible in the transcript
            // (the visible text is unaffected) and wrong in the log.
            let reasoning = delta
                .get("reasoning_content")
                .or_else(|| delta.get("reasoning"))
                .and_then(Value::as_str)
                .map(str::to_string)
                .or_else(|| {
                    delta
                        .get("thinking")
                        .and_then(|t| t.get("text"))
                        .and_then(Value::as_str)
                        .map(str::to_string)
                });
            if let Some(text) = reasoning.filter(|t| !t.is_empty()) {
                let index = self.ensure_open(BlockType::Reasoning, out);
                out.push(StreamChunk::ReasoningDelta { index, text });
            }
            if let Some(text) = delta.get("content").and_then(Value::as_str)
                && !text.is_empty()
            {
                let index = self.ensure_open(BlockType::Text, out);
                out.push(StreamChunk::TextDelta {
                    index,
                    text: text.to_string(),
                });
            }
            if let Some(calls) = delta.get("tool_calls").and_then(Value::as_array) {
                for call in calls {
                    self.openai_tool_delta(call, out);
                }
            }
        }
        if let Some(reason) = choice.get("finish_reason").and_then(Value::as_str) {
            self.close_open(out);
            if let Some(finish) = finish_from_wire(ProviderKind::OpenAiChat, reason) {
                // Deferred, not emitted: this frame is followed by the usage
                // trailer, and the seam's contract is that a stream *ends* with
                // its finish chunk.
                self.pending_finish = Some(finish);
            }
        }
    }

    fn openai_tool_delta(&mut self, call: &Value, out: &mut Vec<StreamChunk>) {
        // Chat tool deltas carry a wire `index` that is authoritative and
        // distinct from the block index; the id may arrive only on the first
        // delta for that call.
        let wire_index = call.get("index").and_then(Value::as_u64).unwrap_or(0);
        let id = call
            .get("id")
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string();
        let name = call
            .pointer("/function/name")
            .and_then(Value::as_str)
            .map(str::to_string);
        let args = call
            .pointer("/function/arguments")
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string();

        // The block index is allocated per tool call and remembered, because
        // later deltas for the same call frequently omit both `id` and `index`
        // and would otherwise open a fresh block per fragment.
        let key = if id.is_empty() {
            format!("idx:{wire_index}")
        } else {
            id.clone()
        };
        let index = match self.tool_index.get(&key) {
            Some(index) => *index,
            None => {
                let index = self.ensure_open(BlockType::ToolCall, out);
                self.tool_index.insert(key, index);
                index
            }
        };
        if name.is_some() || !args.is_empty() || !id.is_empty() {
            out.push(StreamChunk::ToolCallDelta {
                index,
                id,
                name,
                arguments_delta: args,
            });
        }
    }

    /// Responses events, dispatched on the `event:` name with the payload's
    /// own `type` as a cross-check.
    fn responses_frame(&mut self, event: Option<&str>, value: &Value, out: &mut Vec<StreamChunk>) {
        let ty = value
            .get("type")
            .and_then(Value::as_str)
            .or(event)
            .unwrap_or_default();
        match ty {
            "response.output_text.delta" => {
                if let Some(text) = value.get("delta").and_then(Value::as_str) {
                    let index = self.ensure_open(BlockType::Text, out);
                    out.push(StreamChunk::TextDelta {
                        index,
                        text: text.to_string(),
                    });
                }
            }
            "response.reasoning_summary_text.delta" | "response.reasoning_text.delta" => {
                if let Some(text) = value.get("delta").and_then(Value::as_str) {
                    let index = self.ensure_open(BlockType::Reasoning, out);
                    out.push(StreamChunk::ReasoningDelta {
                        index,
                        text: text.to_string(),
                    });
                }
            }
            "response.output_item.added" => {
                if let Some(item) = value.get("item")
                    && item.get("type").and_then(Value::as_str) == Some("function_call")
                {
                    let key = item
                        .get("call_id")
                        .and_then(Value::as_str)
                        .or_else(|| item.get("id").and_then(Value::as_str))
                        .unwrap_or_default()
                        .to_string();
                    let index = self.ensure_open(BlockType::ToolCall, out);
                    self.tool_index.insert(key, index);
                    out.push(StreamChunk::ToolCallDelta {
                        index,
                        id: item
                            .get("call_id")
                            .and_then(Value::as_str)
                            .unwrap_or_default()
                            .to_string(),
                        name: item.get("name").and_then(Value::as_str).map(str::to_string),
                        arguments_delta: String::new(),
                    });
                }
            }
            "response.function_call_arguments.delta" => {
                if let Some(text) = value.get("delta").and_then(Value::as_str) {
                    // The delta names only the item; recover the block by the
                    // call id it was opened under.
                    let key = value
                        .get("call_id")
                        .or_else(|| value.get("item_id"))
                        .and_then(Value::as_str)
                        .unwrap_or_default()
                        .to_string();
                    let index = self
                        .tool_index
                        .get(&key)
                        .copied()
                        .unwrap_or_else(|| self.ensure_open(BlockType::ToolCall, out));
                    out.push(StreamChunk::ToolCallDelta {
                        index,
                        id: key,
                        name: None,
                        arguments_delta: text.to_string(),
                    });
                }
            }
            "response.completed" | "response.incomplete" | "response.failed" => {
                let response = value.get("response").unwrap_or(value);
                if let Some(usage) = response.get("usage").filter(|u| !u.is_null()) {
                    out.push(StreamChunk::Usage {
                        usage: normalize_usage(ProviderKind::OpenAiResponses, usage),
                    });
                }
                self.close_open(out);
                let reason = match ty {
                    "response.completed" => {
                        // A completed response that emitted a function call is
                        // a tool-calls turn even though the status spells
                        // "completed".
                        if self.tool_index.is_empty() {
                            FinishReason::Stop
                        } else {
                            FinishReason::ToolCalls
                        }
                    }
                    // `incomplete` is only ever a truncation on this surface:
                    // the other cause, a content filter, surfaces as `failed`.
                    "response.incomplete" => FinishReason::MaxTokens,
                    _ => {
                        let message = response
                            .get("error")
                            .and_then(|e| e.get("message"))
                            .and_then(Value::as_str)
                            .unwrap_or("provider reported a failed response")
                            .to_string();
                        let code = response
                            .get("error")
                            .and_then(|e| e.get("code"))
                            .and_then(Value::as_str)
                            .unwrap_or("RESPONSE_FAILED")
                            .to_string();
                        FinishReason::Error { message, code }
                    }
                };
                self.finished = true;
                out.push(StreamChunk::Finish { reason });
            }
            _ => {}
        }
    }

    /// Anthropic's event stream: explicit blocks, so `content_block_*` maps
    /// one-to-one onto the seam's block vocabulary.
    fn anthropic_frame(&mut self, value: &Value, out: &mut Vec<StreamChunk>) {
        let ty = value
            .get("type")
            .and_then(Value::as_str)
            .unwrap_or_default();
        let index = value.get("index").and_then(Value::as_u64).unwrap_or(0);
        match ty {
            "message_start" => {
                // Anthropic reports input tokens once, up front, before any
                // content — so it cannot ride the trailing usage chunk alone.
                if let Some(n) = value
                    .pointer("/message/usage/input_tokens")
                    .and_then(Value::as_u64)
                {
                    self.input_tokens = Some(n);
                }
            }
            "content_block_start" => {
                let block = value.get("content_block").unwrap_or(&Value::Null);
                let block_type = match block.get("type").and_then(Value::as_str) {
                    Some("text") => BlockType::Text,
                    Some("thinking") | Some("redacted_thinking") => BlockType::Reasoning,
                    Some("tool_use") => BlockType::ToolCall,
                    // An unknown block type is skipped rather than guessed: a
                    // future block would otherwise be mistranslated into a
                    // wrong one and silently corrupt the recorded stream.
                    _ => return,
                };
                self.close_open(out);
                self.open = Some((index, block_type));
                self.next_index = self.next_index.max(index + 1);
                out.push(StreamChunk::BlockStart { index, block_type });
                // A tool_use block announces its id and name here, and the
                // fragments start empty.
                if block_type == BlockType::ToolCall {
                    let id = block
                        .get("id")
                        .and_then(Value::as_str)
                        .unwrap_or_default()
                        .to_string();
                    self.tool_index.insert(id.clone(), index);
                    out.push(StreamChunk::ToolCallDelta {
                        index,
                        id,
                        name: block
                            .get("name")
                            .and_then(Value::as_str)
                            .map(str::to_string),
                        arguments_delta: String::new(),
                    });
                }
            }
            "content_block_delta" => {
                let delta = value.get("delta").unwrap_or(&Value::Null);
                match delta.get("type").and_then(Value::as_str) {
                    Some("text_delta") => {
                        if let Some(text) = delta.get("text").and_then(Value::as_str) {
                            out.push(StreamChunk::TextDelta {
                                index,
                                text: text.to_string(),
                            });
                        }
                    }
                    Some("thinking_delta") => {
                        if let Some(text) = delta.get("thinking").and_then(Value::as_str) {
                            out.push(StreamChunk::ReasoningDelta {
                                index,
                                text: text.to_string(),
                            });
                        }
                    }
                    Some("input_json_delta") => {
                        if let Some(text) = delta.get("partial_json").and_then(Value::as_str) {
                            out.push(StreamChunk::ToolCallDelta {
                                index,
                                id: String::new(),
                                name: None,
                                arguments_delta: text.to_string(),
                            });
                        }
                    }
                    // `signature_delta` carries the opaque thinking signature,
                    // which the seam's chunk vocabulary has no field for; the
                    // assembled block's signature arrives on `content_block_stop`.
                    _ => {}
                }
            }
            "content_block_stop" => {
                self.close_open(out);
            }
            "message_delta" => {
                if let Some(usage) = value.get("usage") {
                    let mut usage = normalize_usage(ProviderKind::Anthropic, usage);
                    // Anthropic reports input tokens at `message_start`; the
                    // trailing delta carries only output. Folding them here is
                    // what makes the usage chunk complete on this surface.
                    if let Some(n) = self.input_tokens
                        && usage.get("inputTokens").and_then(Value::as_u64) == Some(0)
                    {
                        usage["inputTokens"] = json!(n);
                    }
                    out.push(StreamChunk::Usage { usage });
                }
                if let Some(reason) = value.pointer("/delta/stop_reason").and_then(Value::as_str) {
                    self.close_open(out);
                    if let Some(finish) = finish_from_wire(ProviderKind::Anthropic, reason) {
                        self.finished = true;
                        out.push(StreamChunk::Finish { reason: finish });
                    }
                }
            }
            "error" => {
                self.close_open(out);
                let message = value
                    .pointer("/error/message")
                    .and_then(Value::as_str)
                    .unwrap_or("provider reported an error")
                    .to_string();
                let code = value
                    .pointer("/error/type")
                    .and_then(Value::as_str)
                    .unwrap_or("PROVIDER_ERROR")
                    .to_uppercase();
                self.finished = true;
                out.push(StreamChunk::Finish {
                    reason: FinishReason::Error { message, code },
                });
            }
            _ => {}
        }
    }
}

/// Rewrite a provider's usage object into the seam's `inputTokens` /
/// `outputTokens` vocabulary.
///
/// The three dialects disagree on both naming and, on Anthropic, on
/// **semantics**: Anthropic's `input_tokens` excludes cached tokens while the
/// other two include them. A cached turn therefore reports fewer fresh input
/// tokens on Anthropic for the same work, and normalizing to the inclusive
/// convention is what makes a recorded turn's cost comparable across
/// providers — the same rule the crate states as a cross-dialect invariant.
fn normalize_usage(kind: ProviderKind, usage: &Value) -> Value {
    let u64_at = |v: &Value, keys: &[&str]| -> u64 {
        keys.iter()
            .find_map(|k| v.get(*k).and_then(Value::as_u64))
            .unwrap_or(0)
    };
    match kind {
        ProviderKind::OpenAiChat => json!({
            "inputTokens": u64_at(usage, &["prompt_tokens"]),
            "outputTokens": u64_at(usage, &["completion_tokens"]),
        }),
        ProviderKind::OpenAiResponses => json!({
            "inputTokens": u64_at(usage, &["input_tokens"]),
            "outputTokens": u64_at(usage, &["output_tokens"]),
        }),
        ProviderKind::Anthropic => {
            let fresh = u64_at(usage, &["input_tokens"]);
            let cache_read = u64_at(usage, &["cache_read_input_tokens"]);
            let cache_write = u64_at(usage, &["cache_creation_input_tokens"]);
            json!({
                "inputTokens": fresh + cache_read + cache_write,
                "outputTokens": u64_at(usage, &["output_tokens"]),
            })
        }
    }
}

/// Decode a complete SSE body into chunks, for a non-incremental caller.
///
/// The tests' entry point: the driver decodes incrementally through
/// [`SseDecoder`] and [`ProviderStreamDecoder`] directly.
#[cfg_attr(not(test), allow(dead_code))]
pub fn decode_stream(kind: ProviderKind, body: &str) -> Vec<StreamChunk> {
    let mut decoder = SseDecoder::new();
    let mut frames = Vec::new();
    decoder.feed(body.as_bytes(), &mut frames);
    decoder.finish(&mut frames);
    let mut stream = ProviderStreamDecoder::new(kind);
    let mut chunks = Vec::new();
    for frame in &frames {
        stream.frame(frame, &mut chunks);
    }
    // Flush a deferred finish reason: a provider that closed without `[DONE]`
    // still ended, and so does one whose last frame was the finish itself.
    stream.end(&mut chunks);
    chunks
}

